-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT account.ID AS ENTITY_ID, account.NAME AS ENTITY_NAME,
       account.REGION, account.CATEGORY, account.RISK_TIER, account.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.CONTACT_COUNT) AS CONTACT_COUNT,
       SUM(observation.REVENUE_PHP) AS REVENUE_PHP,
       SUM(observation.ESCALATION_COUNT) AS ESCALATION_COUNT,
       SUM(observation.BREACH_COUNT) AS BREACH_COUNT,
       SUM(observation.SERVICE_CREDIT) AS SERVICE_CREDIT_COUNT,
       SUM(observation.QA_AUDIT_DUE) AS QA_AUDIT_DUE,
       SUM(observation.QA_AUDIT_DONE) AS QA_AUDIT_DONE,
       100.0 * (SUM(observation.CONTACT_COUNT) - SUM(observation.ESCALATION_COUNT)) / NULLIF(SUM(observation.CONTACT_COUNT), 0) AS CLEAN_CONTACT_PCT,
       100.0 * SUM(observation.BREACH_COUNT) / NULLIF(SUM(observation.ESCALATION_COUNT), 0) AS ESCALATION_BREACH_PCT,
       100.0 * SUM(observation.QA_AUDIT_DONE) / NULLIF(SUM(observation.QA_AUDIT_DUE), 0) AS QA_AUDIT_PCT,
       AVG(observation.REPEAT_CONTACT_PCT) AS AVG_REPEAT_CONTACT_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.ACCOUNT_DAILY observation
JOIN RAW.ACCOUNTS account ON account.ID = observation.ENTITY_ID
GROUP BY account.ID, account.NAME, account.REGION, account.CATEGORY, account.RISK_TIER, account.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(CONTACT_COUNT) AS CONTACT_COUNT, SUM(REVENUE_PHP) AS REVENUE_PHP,
       SUM(ESCALATION_COUNT) AS ESCALATION_COUNT, SUM(BREACH_COUNT) AS BREACH_COUNT,
       100.0 * SUM(BREACH_COUNT) / NULLIF(SUM(ESCALATION_COUNT), 0) AS ESCALATION_BREACH_PCT
FROM RAW.ACCOUNT_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.ESCALATION_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ESCALATION_TYPE, SUM(ESCALATION_COUNT) AS ESCALATION_COUNT,
       SUM(BREACH_COUNT) AS BREACH_COUNT,
       SUM(SERVICE_CREDIT) AS SERVICE_CREDIT_COUNT,
       SUM(REVENUE_PHP) AS EXPOSED_REVENUE_PHP,
       100.0 * SUM(BREACH_COUNT) / NULLIF(SUM(ESCALATION_COUNT), 0) AS ESCALATION_BREACH_PCT
FROM RAW.ACCOUNT_DAILY
WHERE ESCALATION_COUNT > 0
GROUP BY ESCALATION_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(CONTACT_COUNT) AS CONTACTS, SUM(ESCALATION_COUNT) AS ESCALATIONS,
         SUM(BREACH_COUNT) AS BREACHES, SUM(SERVICE_CREDIT) AS CREDITS, SUM(REVENUE_PHP) AS REVENUE_PHP,
         SUM(QA_AUDIT_DUE) AS QA_AUDIT_DUE, SUM(QA_AUDIT_DONE) AS QA_AUDIT_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.ACCOUNT_DAILY
), book AS (SELECT COUNT(*) AS ACCOUNT_COUNT FROM RAW.ACCOUNTS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.AGENT_CERTIFICATIONS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Contacts Without Escalation' AS TITLE,
         100.0 * (CONTACTS - ESCALATIONS) / NULLIF(CONTACTS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Escalations Raised', ESCALATIONS, '' FROM observations
  UNION ALL SELECT 3, 'SLA Breaches', BREACHES, '' FROM observations
  UNION ALL SELECT 4, 'Escalation Breach Rate', 100.0 * BREACHES / NULLIF(ESCALATIONS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Service Credits Issued', CREDITS, '' FROM observations
  UNION ALL SELECT 6, 'Billed Revenue (PHP M)', REVENUE_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Contacts Handled', CONTACTS, '' FROM observations
  UNION ALL SELECT 8, 'QA Audit Compliance', 100.0 * QA_AUDIT_DONE / NULLIF(QA_AUDIT_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Client Accounts Monitored', ACCOUNT_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Agent Certification Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Agents In Certification Training', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.ESCALATION_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
